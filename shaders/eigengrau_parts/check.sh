#!/usr/bin/env bash
# Assemble ../eigengrau.wgsl from the parts and validate it with naga.
# Missing parts are replaced by stubs, so any single part can be checked alone.
#   ./check.sh            validate only
#   ./check.sh --install  also write ../eigengrau.wgsl
#   ./check.sh --emit F   also write the assembled body (stubs allowed) to F, for render.py
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../.." && pwd)
pre="$root/vibe-renderer/src/components/fragment_canvas/fragment_preamble.wgsl"
out=$(mktemp --suffix=.wgsl -p "${XDG_RUNTIME_DIR:-/tmp}")
body=$(mktemp -p "${XDG_RUNTIME_DIR:-/tmp}")
trap 'rm -f "$out" "$body"' EXIT

stub() { awk -v want="$1" '/^\/\/@stub /{on=($2==want); next} on' "$here/stubs.wgsl"; }

{
  echo "// eigengrau.wgsl — GENERATED by shaders/eigengrau_parts/check.sh --install. Edit the parts."
  echo
  for part in cortex perception conductor; do
    f="$here/$part.wgsl"
    if [[ -f "$f" ]]; then cat "$f"
    else
      echo "check.sh: $part.wgsl missing, using stub" >&2
      case $part in cortex) stub cortex ;; perception) stub perceive ;; esac
    fi
    echo
  done
} > "$body"

cat "$pre" "$body" > "$out"
naga "$out" && echo "check.sh: OK ($(wc -l < "$body") lines)"
if [[ "${1:-}" == --emit ]]; then cp "$body" "$2" && echo "check.sh: wrote $2"; fi
if [[ "${1:-}" == --install ]]; then
  for p in cortex perception conductor; do [[ -f "$here/$p.wgsl" ]] || { echo "refusing --install with stubs" >&2; exit 1; }; done
  cp "$body" "$root/shaders/eigengrau.wgsl" && echo "check.sh: wrote shaders/eigengrau.wgsl"
fi
