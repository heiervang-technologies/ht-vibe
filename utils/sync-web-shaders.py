#!/usr/bin/env python3
"""Generate browser shader copies and catalog from the native shader directory."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def sync(root: Path, check: bool = False) -> bool:
    source = root / "shaders"
    web = root / "vibe-web/www"
    shaders = web / "shaders"
    expected = {p.name: p.read_bytes() for p in sorted(source.glob("*.wgsl"))}
    # The default demo is web-only; all other shaders come from shaders/.
    if "default.wgsl" in expected:
        raise SystemExit("default.wgsl is reserved for the web demo")
    expected["default.wgsl"] = (web / "default.wgsl").read_bytes()
    outputs = {shaders / name: data for name, data in expected.items()}
    catalog = sorted(Path(name).stem for name in expected)
    outputs[web / "shader-catalog.js"] = (
        "// Generated by utils/sync-web-shaders.py; do not edit.\n"
        "export const SHADERS = " + json.dumps(catalog, indent=4) + ";\n"
    ).encode()
    stale = [p for p, data in outputs.items() if not p.exists() or p.read_bytes() != data]
    extra = sorted(p for p in shaders.glob("*.wgsl") if p.name not in expected)
    if check:
        for path in stale + extra:
            print(f"Out of sync: {path.relative_to(root)}")
        return not (stale or extra)
    # Refuse to remove unexpected files: they may contain uncommitted work.
    if extra:
        raise SystemExit("Move web-only shaders into shaders/ before syncing: "
                         + ", ".join(p.name for p in extra))
    shaders.mkdir(parents=True, exist_ok=True)
    for path in stale:
        path.write_bytes(outputs[path])
    return True


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Report drift without writing files")
    args = parser.parse_args()
    raise SystemExit(0 if sync(ROOT, args.check) else 1)
